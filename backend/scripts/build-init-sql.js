/**
 * Writes init.sql — one standalone file that builds the whole database.
 *
 *   node scripts/build-init-sql.js
 *
 * init.sql is what you hand to somebody who just wants to run SQL: it creates
 * the database, creates every table, and records the migrations as already
 * applied. It is the same DDL scripts/init-db.js applies, in one runnable file.
 *
 * It is GENERATED, not written by hand. schema.sql stays the single source of
 * truth for table structure — a second hand-maintained copy of nine CREATE
 * TABLE statements would drift from it the first time a column changed, which
 * is exactly the failure this project already had between schema.sql and
 * migrations/. Change schema.sql, run this, commit both.
 *
 * scripts/init-db.js calls this at the end of a successful run, so the file
 * cannot fall behind the schema it was generated from without somebody going
 * out of their way.
 */
const fs = require('fs');
const path = require('path');

const BACKEND = path.join(__dirname, '..');
const SCHEMA = path.join(BACKEND, 'schema.sql');
const MIGRATIONS = path.join(BACKEND, 'migrations');
const OUTPUT = path.join(BACKEND, 'init.sql');

// The default database name. init.sql is a standalone artefact, so it cannot
// read .env — the name is written in, and the header says where to change it.
const DEFAULT_DB = 'kl_electricals';

function build() {
  const schema = fs.readFileSync(SCHEMA, 'utf8').trimEnd();

  const migrations = fs
    .readdirSync(MIGRATIONS)
    .filter((name) => name.endsWith('.sql'))
    .sort();

  const header = `-- KL Electricals — complete database setup, in one file.
--
-- GENERATED by scripts/build-init-sql.js from schema.sql. Do not edit by hand:
-- change schema.sql and re-run \`npm run build-init-sql\`, or just run
-- \`npm run init-db\`, which regenerates this file as it goes.
--
-- Run it whichever way suits you:
--
--   mysql -u root -p < init.sql
--   Get-Content init.sql | mysql -u root -p          # PowerShell
--   ...or open it in MySQL Workbench and hit execute.
--
-- Safe to re-run: every statement is CREATE ... IF NOT EXISTS or INSERT IGNORE,
-- so running it against an existing database changes nothing and drops nothing.
--
-- It creates STRUCTURE ONLY. There is no default user and no seed data — make
-- the first login with:
--
--   npm run create-admin -- --id ADMIN001 --name "Your Name" \\
--     --email you@example.com --password "choose-a-strong-one"
--
-- To use a different database name, change the two lines below and set DB_NAME
-- in backend/.env to match.

CREATE DATABASE IF NOT EXISTS \`${DEFAULT_DB}\`
  CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;

USE \`${DEFAULT_DB}\`;

-- Timestamps are UTC by contract — config/db.js pins every pooled connection to
-- it, and the schema uses DATETIME throughout so nothing is silently converted.
-- Setting it here means a table created by this file from a client in another
-- time zone gets the same defaults the application would have written.
SET time_zone = '+00:00';

-- ---------------------------------------------------------------------------
-- Tables (generated from schema.sql)
-- ---------------------------------------------------------------------------
`;

  const migrationSection = `

-- ---------------------------------------------------------------------------
-- schema_migrations
--
-- scripts/migrate.js records what it has applied here. The tables above were
-- created from the current schema.sql, which already contains everything the
-- files in migrations/ do — so they are marked applied rather than left
-- pending. Running them against this database would fail on columns and
-- indexes that are already present.
--
-- The effect: after this file, \`npm run migrate\` reports "up to date" instead
-- of trying to re-apply history.
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS schema_migrations (
  filename    VARCHAR(255) PRIMARY KEY,
  applied_at  DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

INSERT IGNORE INTO schema_migrations (filename) VALUES
${migrations.map((name) => `  ('${name}')`).join(',\n')};
`;

  fs.writeFileSync(OUTPUT, `${header}\n${schema}\n${migrationSection}`, 'utf8');
  return { output: OUTPUT, migrations };
}

module.exports = { build };

if (require.main === module) {
  const { output, migrations } = build();
  console.log(`[SQL] wrote ${path.relative(process.cwd(), output)}`);
  console.log(`[SQL] ${migrations.length} migration(s) marked applied: ${migrations.join(', ')}`);
}
